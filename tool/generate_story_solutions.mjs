import { readdir, readFile, writeFile } from 'node:fs/promises';

const files = (await readdir('assets/stories')).filter((name) => name.endsWith('.json')).sort();
const rows = [];
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
for (const file of files) {
  const story = JSON.parse(await readFile(`assets/stories/${file}`, 'utf8'));
  const { primaryCulprit, motive, method } = story.truth;
  rows.push(`  (${[story.id, primaryCulprit, motive, method].map(quote).join(',')})`);
}
const output = `-- Generated by node tool/generate_story_solutions.mjs from the bundled stories.\n
create table if not exists public.story_solutions(
  story_id text primary key references public.story_rewards(story_id),
  culprit text not null,
  motive text not null,
  method text not null
);
alter table public.story_solutions enable row level security;
revoke all on public.story_solutions from public, anon, authenticated;
grant select on public.story_solutions to service_role;

insert into public.story_solutions(story_id,culprit,motive,method) values\n${rows.join(',\n')}\non conflict(story_id) do update set culprit=excluded.culprit,
  motive=excluded.motive, method=excluded.method;

create or replace function public.claim_story_reward(
  p_user uuid, p_story text, p_culprit text, p_motive text, p_method text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare r public.story_rewards; n int; xp int := 0;
begin
  select * into r from public.story_rewards where story_id = p_story;
  if not found then raise exception 'NOT_FOUND'; end if;
  if not exists(select 1 from public.story_solutions where story_id=p_story
      and culprit=p_culprit and motive=p_motive and method=p_method) then
    return jsonb_build_object('granted',0,'xpGranted',0,
      'balance',(select balance from public.wallet_accounts where user_id=p_user));
  end if;
  insert into public.story_solves(user_id,story_id) values(p_user,p_story)
    on conflict do nothing;
  get diagnostics n=row_count;
  if n=1 then
    perform public.credit_earned(p_user,'story_first_solve',r.coins,null,'story:'||p_story);
    xp:=public.casebook_grant_season_xp(p_user,'story:'||p_story,r.xp);
  end if;
  return jsonb_build_object('granted',case when n=1 then r.coins else 0 end,
    'xpGranted',xp,'balance',(select balance from public.wallet_accounts where user_id=p_user));
end $$;
revoke all on function public.claim_story_reward(uuid,text,text,text,text) from public,anon,authenticated;
grant execute on function public.claim_story_reward(uuid,text,text,text,text) to service_role;
revoke all on function public.claim_story_reward(uuid,text) from public,anon,authenticated,service_role;
drop function public.claim_story_reward(uuid,text);
`;
await writeFile('supabase/migrations/20261009002000_story_solution_verification.sql', output);
console.log(`Wrote ${rows.length} solutions`);
